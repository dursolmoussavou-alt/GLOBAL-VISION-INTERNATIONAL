create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin' and approved = true
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles(id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''), coalesce(new.email,''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.parcels enable row level security;
alter table public.tariffs enable row level security;

drop policy if exists "profiles own read" on public.profiles;
create policy "profiles own read" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());

drop policy if exists "admin profiles write" on public.profiles;
create policy "admin profiles write" on public.profiles for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "approved users read parcels" on public.parcels;
create policy "approved users read parcels" on public.parcels for select to authenticated
using (exists(select 1 from public.profiles p where p.id = auth.uid() and p.approved = true));

drop policy if exists "users insert parcels" on public.parcels;
create policy "users insert parcels" on public.parcels for insert to authenticated
with check (created_by = auth.uid());

drop policy if exists "owners update parcels" on public.parcels;
create policy "owners update parcels" on public.parcels for update to authenticated
using (created_by = auth.uid() or public.is_admin())
with check (created_by = auth.uid() or public.is_admin());

drop policy if exists "admin delete parcels" on public.parcels;
create policy "admin delete parcels" on public.parcels for delete to authenticated using (public.is_admin());

drop policy if exists "approved users read tariffs" on public.tariffs;
create policy "approved users read tariffs" on public.tariffs for select to authenticated
using (exists(select 1 from public.profiles p where p.id = auth.uid() and p.approved = true));

drop policy if exists "admin tariffs write" on public.tariffs;
create policy "admin tariffs write" on public.tariffs for all to authenticated using (public.is_admin()) with check (public.is_admin());

