create or replace function public.next_parcel_id()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  prefix text := 'GVI-' || to_char(current_date, 'YYMMDD') || '-';
  n integer;
begin
  perform pg_advisory_xact_lock(hashtext(prefix));
  select coalesce(max(substring(id from '[0-9]+$')::integer),0) + 1
  into n from public.parcels where id like prefix || '%';
  return prefix || lpad(n::text,5,'0');
end;
$$;

grant execute on function public.next_parcel_id() to authenticated;


